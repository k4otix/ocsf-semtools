"""Text emission: final, formatter-stable source for enums, Structs and lazy package inits."""

import json
import textwrap
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field

from ocsf_toolkit.codegen.layout import ENUMS, Place
from ocsf_toolkit.codegen.naming import member_names
from ocsf_toolkit.ir import EnumMember, EnumValue

WIDTH = 120  # the line length generated code is formatted for
MARKER = "# Generated by ocsf-toolkit"  # first line of every generated module


@dataclass(frozen=True, slots=True)
class Field:
    """One Struct field as the emitter writes it."""

    name: str  # Python name
    wire: str  # attribute name on the wire
    annotation: str  # value type, without `| None`
    default: str | None  # source text of the default; None means required
    always: bool = False  # always encoded: omit_defaults never drops a default_factory value


@dataclass(frozen=True, slots=True)
class EnumClass:
    """One IntEnum or StrEnum class to emit."""

    name: str
    doc: str
    enum: Mapping[EnumValue, EnumMember]


@dataclass(slots=True)
class Imports:
    """What one module needs, rendered in ruff's isort order."""

    stdlib: dict[str, set[str]] = field(default_factory=dict[str, set[str]])
    msgspec: set[str] = field(default_factory=set[str])
    enums: set[str] = field(default_factory=set[str])
    modules: set[Place] = field(default_factory=set[Place])

    def need(self, module: str, name: str) -> None:
        """Record a ``from module import name`` from the standard library."""
        self.stdlib.setdefault(module, set()).add(name)

    def render(self, here: Place | None) -> list[str]:
        """Return the import block for a module at ``here`` (None for enums.py)."""
        blocks: list[list[str]] = [["from __future__ import annotations"]]
        if self.stdlib:
            blocks.append([_from(m, names) for m, names in sorted(self.stdlib.items())])
        if self.msgspec:
            blocks.append([_from("msgspec", self.msgspec)])
        local: list[tuple[str, str]] = []
        if here is not None:
            if self.enums:
                local.append((ENUMS, _from(f"{here.root}{ENUMS}", self.enums)))
            for target in self.modules:
                module = ".".join(target.package)
                local.append((f"{module} {target.module}", here.import_line(target)))
        if local:
            blocks.append([line for _, line in sorted(local)])
        return [line for block in blocks for line in (*block, "")]


def header(version: str, digest: str) -> list[str]:
    """Return the comment lines that open every generated module."""
    return [f"{MARKER} from OCSF {version}; do not edit.", f"# IR sha256 {digest}"]


def string(text: str) -> str:
    """Return a Python string literal in the quote style ruff format prefers.

    Every control character is escaped, so no input text can end the literal.
    """
    if '"' in text and "'" not in text:
        return repr(text)
    return json.dumps(text, ensure_ascii=False)


def docstring(text: str, indent: str) -> list[str]:
    """Return a docstring as ruff leaves it: one line if it fits, else wrapped paragraphs."""
    # schema text is data: control characters (a \r would end a line) become spaces
    text = "".join(c if c.isprintable() or c == "\n" else " " for c in text)
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"').rstrip()
    if text.endswith('"'):
        text += " "
    one = f'{indent}"""{text}"""'
    if len(one) <= WIDTH and "\n" not in text:
        return [one]
    lines: list[str] = []
    for n, paragraph in enumerate(text.split("\n\n")):
        lead = f'{indent}"""' if n == 0 else indent
        if n:
            lines.append("")
        # 3 short of the width, the room the closing quotes take: a paragraph that fits in one line that
        # way would have fit as a one-liner, which returned above
        lines += textwrap.wrap(
            paragraph,
            WIDTH - 3,
            initial_indent=lead,
            subsequent_indent=indent,
            break_long_words=False,
            break_on_hyphens=False,
        )
    return [*lines, f'{indent}"""']


def enum_class(e: EnumClass, imports: Imports) -> list[str]:
    """Return the lines of one enum class, recording the imports it needs."""
    is_str = any(isinstance(v, str) for v in e.enum)
    base = "StrEnum" if is_str else "IntEnum"
    imports.need("enum", base)
    lines = [f"class {e.name}({base}):", *docstring(e.doc, "    "), ""]
    for value, name in member_names(e.enum).items():
        literal = string(value) if isinstance(value, str) else str(value)
        lines.append(f"    {name} = {literal}")
    return lines


def struct_class(
    name: str,
    doc: str,
    ocsf: tuple[str, str],
    groups: Iterable[tuple[str, list[Field]]],
    imports: Imports,
) -> list[str]:
    """Return the lines of one Struct class, its fields in groups, recording the imports it needs."""
    imports.msgspec.add("Struct")
    head = f"class {name}(Struct, kw_only=True, omit_defaults=True, forbid_unknown_fields=True):"
    if len(head) > WIDTH:
        bases = "Struct, kw_only=True, omit_defaults=True, forbid_unknown_fields=True"
        head = f"class {name}(\n    {bases}\n):"
    lines = [head, *docstring(doc, "    "), ""]
    lines.append(f"    __ocsf__ = ({string(ocsf[0])}, {string(ocsf[1])})")
    for comment, fields in groups:
        if fields:
            lines += ["", f"    # {comment}"]
            for f in fields:
                lines += _field(f, imports)
    return lines


def render_module(
    header_lines: list[str], doc: str, imports: Imports, here: Place | None, bodies: list[list[str]]
) -> str:
    """Return a module of enums and Structs: the header comment, a docstring, imports, then the bodies."""
    lines = [*header_lines, *docstring(doc, ""), "", *imports.render(here)]
    for body in bodies:
        lines += ["", *body, ""]
    return _finish(lines)


def lazy_init(
    header_lines: list[str],
    doc: str,
    exports: list[Place],
    here: tuple[str, ...],
    dunders: list[str],
) -> str:
    """Return a package __init__ that type checkers read statically and Python imports on demand."""
    lines = [*header_lines, *docstring(doc, ""), ""]
    if exports:
        lines += ["import importlib", "from typing import TYPE_CHECKING", "", "if TYPE_CHECKING:"]
        for p in sorted(exports, key=lambda p: p.module):
            line = f"    from .{_tail(p, here)} import {p.name} as {p.name}"
            if len(line) > WIDTH:
                line = f"    from .{_tail(p, here)} import (\n        {p.name} as {p.name},\n    )"
            lines.append(line)
        lines.append("")
    lines += dunders
    names = sorted(p.name for p in exports)
    if names:
        lines += ["__all__ = [", *(f"    {string(n)}," for n in names), "]"]
        lazy = {p.name: f".{_tail(p, here)}" for p in exports}
        lines += ["_LAZY = {", *(f"    {string(n)}: {string(lazy[n])}," for n in names), "}"]
        lines += [
            "",
            "",
            "def __getattr__(name: str) -> object:",
            "    try:",
            "        module = _LAZY[name]",
            "    except KeyError:",
            '        message = f"module {__name__!r} has no attribute {name!r}"',
            "        raise AttributeError(message) from None",
            "    value = getattr(importlib.import_module(module, __name__), name)",
            "    globals()[name] = value",
            "    return value",
            "",
            "",
            "def __dir__() -> list[str]:",
            "    return sorted([*globals(), *_LAZY])",
        ]
    else:
        lines.append("__all__: list[str] = []")
    return _finish(lines)


def _finish(lines: list[str]) -> str:
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


def _tail(p: Place, here: tuple[str, ...]) -> str:
    return ".".join((*p.package[len(here) :], p.module))


def _field(f: Field, imports: Imports) -> list[str]:
    """Return one field, wrapped the way ruff format wraps an over-long annotated assignment."""
    annotation = f.annotation if f.default != "None" else f"{f.annotation} | None"
    default = f.default
    if f.name != f.wire or f.always:
        imports.msgspec.add("field")
        args = [] if f.default is None else [f"default={f.default}"]
        if f.always:
            args = [f"default_factory=lambda: {f.default}"]
        if f.name != f.wire:
            args.append(f"name={string(f.wire)}")
        default = f"field({', '.join(args)})"
    tail = "" if default is None else f" = {default}"
    line = f"    {f.name}: {annotation}{tail}"
    if len(line) <= WIDTH:
        return [line]
    if default is not None and default.startswith("field("):
        opening = f"    {f.name}: {annotation} = field("
        inner = f"        {default.removeprefix('field(').removesuffix(')')}"
        if len(opening) <= WIDTH and len(inner) <= WIDTH:
            return [opening, inner, "    )"]
    if tail and len(f"        {annotation}") <= WIDTH:
        return [f"    {f.name}: (", f"        {annotation}", f"    ){tail}"]
    inner = annotation.removeprefix("list[").removesuffix("]")
    if not tail and annotation.startswith("list[") and len(f"        {inner}") <= WIDTH:
        return [f"    {f.name}: list[", f"        {inner}", "    ]"]
    return [f"{line}  # noqa: E501"]


def _from(module: str, names: set[str]) -> str:
    ordered = sorted(names, key=lambda n: (not n.isupper(), not n[:1].isupper(), n.lower(), n))
    line = f"from {module} import {', '.join(ordered)}"
    if len(line) <= WIDTH:
        return line
    return "\n".join([f"from {module} import (", *(f"    {n}," for n in ordered), ")"])
