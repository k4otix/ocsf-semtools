"""Release tooling for the model dists: render a dist's project files, check built wheels against
the lockfile, and list the dists whose generated tree is not on PyPI yet.

Run from the repository root with ``uv run python packaging/version_dist/dist.py ACTION``.
"""

import argparse
import io
import json
import re
import shutil
import sys
import urllib.error
import urllib.request
import zipfile
from pathlib import Path

from ocsf_toolkit.cli import lock
from ocsf_toolkit.cli.models import files_sha256, package_name

HERE = Path(__file__).parent
ROOT = HERE.parent.parent
PYPI = "https://pypi.org/pypi/{}/json"


def core_range(version: str) -> str:
    """The core versions a dist generated by core ``version`` runs on: that one up to the next
    generated-code contract break (the next minor before 1.0, the next major after)."""
    base = version.split("+", 1)[0]  # a local version can't appear in a >= specifier
    match = re.match(r"(\d+)\.(\d+)", base)
    if match is None:
        raise ValueError(f"not a release or dev version: {version!r}")
    major, minor = int(match[1]), int(match[2])
    upper = f"0.{minor + 1}" if major == 0 else f"{major + 1}"
    return f">={base},<{upper}"


def dist_name(version: str) -> str:
    return package_name(version).replace("_", "-")


def render(ocsf: str, version: str, out: Path) -> None:
    """Write pyproject.toml, README.md and LICENSE into a dist directory."""
    values = {
        "@DIST@": dist_name(ocsf),
        "@PACKAGE@": package_name(ocsf),
        "@OCSF@": ocsf,
        "@VERSION@": version,
        "@CORE@": core_range(version),
    }
    for name in ("pyproject.toml", "README.md"):
        text = (HERE / f"{name}.tmpl").read_text(encoding="utf-8")
        for key, value in values.items():
            text = text.replace(key, value)
        (out / name).write_text(text, encoding="utf-8")
    shutil.copyfile(ROOT / "LICENSE", out / "LICENSE")


def wheel_tree(wheel: Path | bytes, package: str) -> dict[str, bytes]:
    """The files of ``package`` inside a wheel, by path relative to the package."""
    source = wheel if isinstance(wheel, Path) else io.BytesIO(wheel)
    prefix = f"{package}/"
    with zipfile.ZipFile(source) as z:
        return {
            n.removeprefix(prefix): z.read(n)
            for n in z.namelist()
            if n.startswith(prefix) and not n.endswith("/")
        }


def _window() -> list[lock.SchemaEntry]:
    return [e for e in lock.read(ROOT / "ocsf.lock").schemas if e.ship_models]


def check_wheels(wheels: list[Path]) -> None:
    """Every model-window dist has exactly one wheel here, holding the tree the lockfile pins."""
    for entry in _window():
        package = package_name(entry.version)
        found = [w for w in wheels if w.name.startswith(f"{package}-")]
        if len(found) != 1:
            raise ValueError(f"expected one {package} wheel, found {[w.name for w in found]}")
        if files_sha256(wheel_tree(found[0], package)) != entry.models_tree_sha256:
            raise ValueError(f"{found[0].name} does not hold the tree the lockfile pins")
        print(f"{found[0].name}: ok  tree == models_tree_sha256 {entry.models_tree_sha256}")


def unpublished() -> list[str]:
    """Model-window versions whose latest wheel on PyPI holds a different tree (or none)."""
    out: list[str] = []
    for entry in _window():
        package = package_name(entry.version)
        try:
            with urllib.request.urlopen(PYPI.format(dist_name(entry.version))) as response:
                info = json.load(response)
        except urllib.error.HTTPError as exc:
            if exc.code != 404:
                raise
            out.append(entry.version)  # never published
            continue
        urls = [u["url"] for u in info["urls"] if u["packagetype"] == "bdist_wheel"]
        if len(urls) != 1:
            raise ValueError(f"{dist_name(entry.version)} {info['info']['version']}: {urls}")
        with urllib.request.urlopen(urls[0]) as response:
            published = files_sha256(wheel_tree(response.read(), package))
        if published != entry.models_tree_sha256:
            out.append(entry.version)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="dist.py", description=__doc__)
    actions = parser.add_subparsers(dest="action", required=True)
    r = actions.add_parser("render", help="write a dist's pyproject.toml, README.md and LICENSE")
    r.add_argument("--ocsf", required=True)
    r.add_argument("--version", required=True, help="the core version generating the dist")
    r.add_argument("--out", required=True, type=Path)
    c = actions.add_parser("check-wheels", help="assert the built wheels hold the pinned trees")
    c.add_argument("wheels", nargs="+", type=Path)
    actions.add_parser("unpublished", help="print versions whose tree is not on PyPI")
    args = parser.parse_args(argv)
    if args.action == "render":
        render(args.ocsf, args.version, args.out)
    elif args.action == "check-wheels":
        check_wheels(args.wheels)
    else:
        print(" ".join(unpublished()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
