"""Release tooling for the model dists: render a dist's project files, check built wheels against
the lockfile, list the dists a core release has to publish again, and run released dists
against the core in this checkout.

Run from the repository root with ``uv run python packaging/version_dist/dist.py ACTION``.
"""

import argparse
import io
import json
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.error
import urllib.request
import zipfile
from pathlib import Path

from ocsf_toolkit.cli import lock
from ocsf_toolkit.cli.models import files_sha256, package_name

HERE = Path(__file__).parent
ROOT = HERE.parent.parent
PYPI = "https://pypi.org/pypi/{}/json"


def core_range(version: str) -> str:
    """The core versions a dist generated by core ``version`` runs on: that one up to the next
    generated-code contract break (the next minor before 1.0, the next major after)."""
    base = version.split("+", 1)[0]  # a local version can't appear in a >= specifier
    match = re.match(r"(\d+)\.(\d+)", base)
    if match is None:
        raise ValueError(f"not a release or dev version: {version!r}")
    major, minor = int(match[1]), int(match[2])
    upper = f"0.{minor + 1}" if major == 0 else f"{major + 1}"
    return f">={base},<{upper}"


def dist_name(version: str) -> str:
    return package_name(version).replace("_", "-")


def render(ocsf: str, version: str, out: Path) -> None:
    """Write pyproject.toml, README.md and LICENSE into a dist directory."""
    values = {
        "@DIST@": dist_name(ocsf),
        "@PACKAGE@": package_name(ocsf),
        "@OCSF@": ocsf,
        "@VERSION@": version,
        "@CORE@": core_range(version),
    }
    for name in ("pyproject.toml", "README.md"):
        text = (HERE / f"{name}.tmpl").read_text(encoding="utf-8")
        for key, value in values.items():
            text = text.replace(key, value)
        (out / name).write_text(text, encoding="utf-8")
    shutil.copyfile(ROOT / "LICENSE", out / "LICENSE")


def wheel_tree(wheel: Path | bytes, package: str) -> dict[str, bytes]:
    """The files of ``package`` inside a wheel, by path relative to the package."""
    source = wheel if isinstance(wheel, Path) else io.BytesIO(wheel)
    prefix = f"{package}/"
    with zipfile.ZipFile(source) as z:
        return {n.removeprefix(prefix): z.read(n) for n in z.namelist() if n.startswith(prefix) and not n.endswith("/")}


def _window() -> list[lock.SchemaEntry]:
    return [e for e in lock.read(ROOT / "ocsf.lock").schemas if e.ship_models]


def check_wheels(wheels: list[Path]) -> None:
    """Every model-window dist has exactly one wheel here, holding the tree the lockfile pins."""
    for entry in _window():
        package = package_name(entry.version)
        found = [w for w in wheels if w.name.startswith(f"{package}-")]
        if len(found) != 1:
            raise ValueError(f"expected one {package} wheel, found {[w.name for w in found]}")
        if files_sha256(wheel_tree(found[0], package)) != entry.models_tree_sha256:
            raise ValueError(f"{found[0].name} does not hold the tree the lockfile pins")
        print(f"{found[0].name}: ok  tree == models_tree_sha256 {entry.models_tree_sha256}")


def _release(version: str) -> tuple[int, ...]:
    match = re.match(r"\d+(\.\d+)*", version)
    if match is None:
        raise ValueError(f"not a version: {version!r}")
    return tuple(int(p) for p in match[0].split("."))


def admits(wheel: bytes, core: str) -> bool:
    """Whether a published dist wheel's ``ocsf-toolkit`` requirement allows core version ``core``
    (only the upper bound can exclude a newer core; the lower bound was met when it shipped)."""
    with zipfile.ZipFile(io.BytesIO(wheel)) as z:
        (metadata,) = [n for n in z.namelist() if n.endswith(".dist-info/METADATA")]
        text = z.read(metadata).decode()
    found = re.search(r"^Requires-Dist: ocsf-toolkit\b(.*)$", text, re.MULTILINE)
    if found is None:
        raise ValueError(f"{metadata} does not require ocsf-toolkit")
    upper = re.search(r"<\s*([0-9.]+)", found[1])
    if upper is None:
        return False  # an exact pin from before ranges: never admits another core
    bound, release = _release(upper[1]), _release(core)
    width = max(len(bound), len(release))
    return release + (0,) * (width - len(release)) < bound + (0,) * (width - len(bound))


def needs_release(published: bytes | None, package: str, tree_sha256: str, core: str) -> bool:
    """A dist is released again when PyPI has none, holds another tree, or excludes this core."""
    if published is None:
        return True
    return files_sha256(wheel_tree(published, package)) != tree_sha256 or not admits(published, core)


def _latest_wheel(dist: str) -> tuple[str, bytes] | None:
    """(file name, bytes) of the newest release's wheel on PyPI, or None if never published."""
    try:
        with urllib.request.urlopen(PYPI.format(dist)) as response:
            info = json.load(response)
    except urllib.error.HTTPError as exc:
        if exc.code == 404:
            return None
        raise
    files = [u for u in info["urls"] if u["packagetype"] == "bdist_wheel"]
    if len(files) != 1:
        raise ValueError(f"{dist} {info['info']['version']}: expected one wheel, got {files}")
    with urllib.request.urlopen(files[0]["url"]) as response:
        data: bytes = response.read()
    return files[0]["filename"], data


def unpublished(core: str) -> list[str]:
    """Model-window versions to release alongside core version ``core``."""
    out: list[str] = []
    for e in _window():
        latest = _latest_wheel(dist_name(e.version))
        wheel = None if latest is None else latest[1]
        if needs_release(wheel, package_name(e.version), e.models_tree_sha256, core):
            out.append(e.version)
    return out


# Builds and parses one event with each released dist against the core under test: the promise
# that lets a dist require a range of core versions is that newer core still runs older dists.
SMOKE = """
import sys
from datetime import datetime, timezone
import msgspec
from ocsf_toolkit import build, parse
models = __import__(sys.argv[1])
cls = models.DetectionFinding
o = models.objects
event = build(
    cls,
    activity_id=models.classes.detection_finding.DetectionFindingActivityId.CREATE,
    severity_id=models.enums.SeverityId.HIGH,
    time=1_700_000_000_000,
    metadata=o.Metadata(product=o.Product(name="p", vendor_name="v")),
    finding_info={"uid": "f-1", "title": "t"},
)
assert event.type_uid == event.class_uid * 100 + 1, event.type_uid
back, report = parse(msgspec.to_builtins(event), as_=cls)
assert back == event, report
print(f"{sys.argv[1]}: build and parse ok against ocsf-toolkit", file=sys.stderr)
"""


def compat(core: str, local: Path | None) -> None:
    """Install the core at ``ROOT`` (version ``core``) into a fresh venv with each model-window
    dist as released - from PyPI, or from wheels in ``local`` - and run SMOKE against each."""
    with tempfile.TemporaryDirectory() as tmp:
        work = Path(tmp)
        python = _venv(work / "venv")
        for e in _window():
            package = package_name(e.version)
            if local is not None:
                paths = sorted(local.glob(f"{package}-*.whl"))
                if len(paths) != 1:
                    raise ValueError(f"expected one {package} wheel in {local}, found {paths}")
                found: tuple[str, bytes] | None = (paths[0].name, paths[0].read_bytes())
            else:
                found = _latest_wheel(dist_name(e.version))
            if found is None:
                print(f"{e.version}: not published yet; nothing to check")
                continue
            name, data = found
            if not admits(data, core):
                print(f"{e.version}: {name} excludes core {core}; it is republished with it")
                continue
            (work / name).write_bytes(data)
            _uv("pip", "install", "--quiet", "--no-deps", "--python", python, str(work / name))
            subprocess.run([python, "-I", "-c", SMOKE, package], check=True)
            print(f"{e.version}: {name} runs on core {core}")


def _venv(path: Path) -> str:
    _uv("venv", "--quiet", str(path))
    python = str(path / "bin" / "python")
    _uv("pip", "install", "--quiet", "--python", python, str(ROOT))
    return python


def _uv(*args: str) -> None:
    subprocess.run(["uv", *args], check=True)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="dist.py", description=__doc__)
    actions = parser.add_subparsers(dest="action", required=True)
    r = actions.add_parser("render", help="write a dist's pyproject.toml, README.md and LICENSE")
    r.add_argument("--ocsf", required=True)
    r.add_argument("--version", required=True, help="the core version generating the dist")
    r.add_argument("--out", required=True, type=Path)
    c = actions.add_parser("check-wheels", help="assert the built wheels hold the pinned trees")
    c.add_argument("wheels", nargs="+", type=Path)
    u = actions.add_parser("unpublished", help="print the model-window versions PyPI lacks for this core release")
    u.add_argument("--version", required=True, help="the core version being released")
    k = actions.add_parser("compat", help="run each released dist against this core")
    k.add_argument("--version", required=True, help="the version of the core in this checkout")
    k.add_argument("--wheels", type=Path, help="use dist wheels from here instead of PyPI")
    args = parser.parse_args(argv)
    if args.action == "render":
        render(args.ocsf, args.version, args.out)
    elif args.action == "check-wheels":
        check_wheels(args.wheels)
    elif args.action == "compat":
        compat(args.version, args.wheels)
    else:
        print(" ".join(unpublished(args.version)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
